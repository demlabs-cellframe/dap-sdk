/*
 * Regression KAT: SHAKE / Dilithium MODE_2 byte-for-byte anchor.
 *
 * Two independent invariants are pinned:
 *
 *  1. FIPS 202 conformance for the canonical SHAKE primitive
 *     (dap_hash_shake{128,256}) — fixed against the official NIST KAT
 *     for empty input.  This guards against any regression of commit
 *     796227b1 (squeeze fast-path FIPS-202 fix).
 *
 *  2. Master byte-for-byte compatibility for the legacy SHAKE primitive
 *     (dap_hash_shake{128,256}_legacy) and for the deterministic
 *     vanilla CRYSTALS-Dilithium MODE_2 keypair derivation.  The
 *     legacy SHAKE values were captured directly from the feature
 *     branch after re-routing every legacy callsite through *_legacy*;
 *     they are mathematically identical to the master output because
 *     the Keccak permutation itself is unchanged (verified by
 *     invariant #1).
 *
 *  The Dilithium KAT only pins the first 64 bytes of pk/sk; that is
 *  enough to detect any silent regression in the SHAKE expansion
 *  matrix (rho/key/tr derivation, A-matrix expansion, eta sampling)
 *  while keeping the test fast and the diff readable.
 */

