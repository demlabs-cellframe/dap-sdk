static void s_test_shake_canonical_fips202(void)
{
    dap_print_module_name("FIPS 202 SHAKE canonical KAT");

    uint8_t out128[64], out256[64];
    dap_hash_shake128(out128, sizeof(out128), (const uint8_t *)"", 0);
    dap_hash_shake256(out256, sizeof(out256), (const uint8_t *)"", 0);

    dap_assert_PIF(
        memcmp(out128, k_shake128_empty_canonical, sizeof(out128)) == 0,
        "SHAKE128(\"\", 64) MUST match the FIPS 202 reference vector");
    dap_pass_msg("SHAKE128(empty, 64) matches FIPS 202 KAT");

    dap_assert_PIF(
        memcmp(out256, k_shake256_empty_canonical, sizeof(out256)) == 0,
        "SHAKE256(\"\", 64) MUST match the FIPS 202 reference vector");
    dap_pass_msg("SHAKE256(empty, 64) matches FIPS 202 KAT");
}

static void s_test_shake_legacy_master_compat(void)
{
    dap_print_module_name("Legacy SHAKE master compat KAT");

    uint8_t out128[64], out256[64];
    dap_hash_shake128_legacy(out128, sizeof(out128), (const uint8_t *)"", 0);
    dap_hash_shake256_legacy(out256, sizeof(out256), (const uint8_t *)"", 0);

    dap_assert_PIF(
        memcmp(out128, k_shake128_empty_legacy, sizeof(out128)) == 0,
        "SHAKE128_legacy(\"\", 64) MUST reproduce the master byte stream");
    dap_pass_msg("SHAKE128_legacy(empty, 64) matches master pre-FIPS bytes");

    dap_assert_PIF(
        memcmp(out256, k_shake256_empty_legacy, sizeof(out256)) == 0,
        "SHAKE256_legacy(\"\", 64) MUST reproduce the master byte stream");
    dap_pass_msg("SHAKE256_legacy(empty, 64) matches master pre-FIPS bytes");
}

static void s_test_dilithium_mode2_legacy_keypair(void)
{
    dap_print_module_name("Vanilla Dilithium-2 deterministic keypair KAT");

    dilithium_public_key_t  pk;
    dilithium_private_key_t sk;
    memset(&pk, 0, sizeof(pk));
    memset(&sk, 0, sizeof(sk));

    int rc = dilithium_crypto_sign_keypair(&pk, &sk, MODE_2,
                                           k_seed, sizeof(k_seed));
    dap_assert_PIF(rc == 0, "Dilithium-2 keypair generation MUST succeed");
    dap_assert_PIF(pk.data && sk.data, "key buffers MUST be allocated");

    dap_assert_PIF(
        memcmp(pk.data, k_dilithium2_pk_prefix64, 64) == 0,
        "Dilithium-2 pk[0..64] MUST match the master byte-for-byte anchor");
    dap_pass_msg("Dilithium-2 pk[0..64] matches master anchor");

    dap_assert_PIF(
        memcmp(sk.data, k_dilithium2_sk_prefix64, 64) == 0,
        "Dilithium-2 sk[0..64] MUST match the master byte-for-byte anchor");
    dap_pass_msg("Dilithium-2 sk[0..64] matches master anchor");

    /* sk and pk MUST share the same 32-byte rho prefix. */
    dap_assert_PIF(memcmp(pk.data, sk.data, 32) == 0,
                   "rho prefix in pk and sk MUST match (FIPS layout)");
    dap_pass_msg("rho prefix consistent between pk and sk");
}

int main(void)
{
    s_test_shake_canonical_fips202();
    s_test_shake_legacy_master_compat();
    s_test_dilithium_mode2_legacy_keypair();

    return 0;
}
