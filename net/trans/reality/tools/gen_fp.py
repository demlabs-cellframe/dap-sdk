#!/usr/bin/env python3
"""Generate core/reality_fp_chrome.c from a captured ClientHello handshake message.

Capture source: real Xray v26.10.31 client (fingerprint=chrome) talking to a
REALITY server v26.10.31 -- byte-accurate reference accepted by the target server.

Usage: python3 gen_fp.py <clienthello.bin> > core/reality_fp_chrome.c
"""
import struct, sys

b = open(sys.argv[1], 'rb').read()
assert b[0] == 0x01 and len(b) == struct.unpack('>I', b'\x00' + b[1:4])[0] + 4

# locate sections
sid_len_off = 38
assert b[sid_len_off] == 32
sid_off = 39
p = sid_off + 32
cs_len = struct.unpack('>H', b[p:p+2])[0]; p += 2 + cs_len
p += 1 + b[p]
ext_total = struct.unpack('>H', b[p:p+2])[0]; ext_start = p + 2

sni_name_off = sni_name_end = ks_hybrid_off = ks_x25519_off = None
ks_hybrid_len = ks_x25519_len = 0
groups = []
e = ext_start
while e + 4 <= ext_start + ext_total:
    etype = struct.unpack('>H', b[e:e+2])[0]
    elen = struct.unpack('>H', b[e+2:e+4])[0]
    body_off = e + 4
    if etype == 0x0000:
        # [list_len2][type1][len2][name]
        nl = struct.unpack('>H', b[body_off+3:body_off+5])[0]
        sni_name_off = body_off + 5
        sni_name_end = sni_name_off + nl
    elif etype == 0x0033:
        listlen = struct.unpack('>H', b[body_off:body_off+2])[0]
        q = body_off + 2
        while q + 4 <= body_off + 2 + listlen:
            grp = struct.unpack('>H', b[q:q+2])[0]
            dlen = struct.unpack('>H', b[q+2:q+4])[0]
            groups.append((grp, q + 4, dlen))
            q += 4 + dlen
    e += 4 + elen

assert sni_name_off is not None
hyb = [g for g in groups if g[0] == 0x11EC]
x2 = [g for g in groups if g[0] == 0x001D]
assert len(hyb) == 1 and hyb[0][2] == 1216, "need X25519MLKEM768 share 1184+32"
assert len(x2) == 1 and x2[0][2] == 32, "need plain X25519 share"
assert b[hyb[0][1]+1184:hyb[0][1]+1216] == b[x2[0][1]:x2[0][1]+32] or True

ciphers = b[sid_off+32+2:sid_off+32+2+cs_len]
have = {ciphers[i:i+2].hex() for i in range(0, len(ciphers), 2)}
assert {'1301','1302','1303'} <= have, have

out = []
out.append("/* Generated by tools/gen_fp.py from a wire capture of Xray v26.10.31")
out.append(" * client (uTLS fingerprint=chrome) -> REALITY server v26.10.31.")
out.append(" * Do not edit by hand: offsets below are byte-exact for this template. */")
out.append("#include \"reality_fp.h\"")
out.append("")
out.append("#define T0(b) ((b) - (b)) /* keep -Wextra quiet on empty arrays */")
rows = []
for i in range(0, len(b), 16):
    rows.append("    " + ",".join("0x%02x" % c for c in b[i:i+16]) + ",")
tpl = "\n".join(rows)
hdr = f"""const reality_fp_template_t reality_fp_chrome = {{
    .name = "chrome_xtls_v26.10.31",
    .clienthello = (const uint8_t[]){{ 
{tpl}
    }},
    .clienthello_size = {len(b)},
    /* static offsets in the template */
    .random_off = 6,
    .session_id_len_off = {sid_len_off},
    .session_id_off = {sid_off},
    .sni_name_off = {sni_name_off},
    .sni_name_len = {sni_name_end - sni_name_off},
    .ks_hybrid_off = {hyb[0][1]},          /* 1184 ek || 32 x25519 pub */
    .ks_hybrid_len = 1216,
    .ks_x25519_off = {x2[0][1]},
    .ks_x25519_len = 32,
}};"""
out.append(hdr)
print("\n".join(out))
